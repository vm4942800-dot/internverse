def get_all_internships() -> List[Internship]:
    """Return all internships from Supabase, falling back to local data."""
    from internship_agent.supabase_client import fetch_internships

    remote = fetch_internships()
    return remote if remote is not None else INTERNSHIPS


def get_internship_by_id(internship_id: str) -> Internship | None:
    """Look up an internship by its ID."""
    for i in get_all_internships():
        if i.id == internship_id:
            return i
    return None
